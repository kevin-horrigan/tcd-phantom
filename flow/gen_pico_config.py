# -*- coding: utf-8 -*-
"""Write pico/config.py from the model, so the Pico cannot disagree with it.

    python gen_pico_config.py

Every number the firmware needs is derived somewhere in syringe_drive.py or
assembly.py, and all of them move when the syringe changes. Retyping them into
the firmware is how a rig ends up commanding a 4.38 mm beat through a barrel
that needs 4.17: nothing errors, the volume is quietly 5 percent wrong, and
the only symptom is a waveform that does not match the model it was supposed
to reproduce.

So this file is GENERATED. Do not hand-edit pico/config.py. Change the model,
re-run this, re-upload.

The one thing here that is NOT from the model is DIR_ADVANCE, because which
way a stepper turns depends on how the coils landed in the connector, and no
amount of modelling knows that. It is a one-bit measurement, and drive.py's
self-test is what measures it.
"""
import os
import sys

import syringe_drive as S
import assembly as A

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "pico", "config.py")

# Proven on hardware 2026-11-08 with the wiring test, and CONFIRMED against
# the motor on 2026-11-10: a commanded 1600 microsteps turned the shaft
# exactly one revolution. Had MS1/MS2 grounded been giving 16, as it does on
# a TMC2208, that command would have turned half a turn and every volume this
# rig delivers would have been out by a factor of two, with a waveform that
# looked entirely healthy. This is the one constant here that is measured
# rather than read off a datasheet, because the two boards look alike.
STEP_PIN, DIR_PIN, EN_PIN = 2, 3, 4
MICROSTEP = 8

TEMPLATE = '''# -*- coding: utf-8 -*-
"""GENERATED by gen_pico_config.py on {date}. Do not edit by hand.

Change syringe_drive.py, re-run the generator, re-upload. Hand edits are lost
and, worse, make the firmware disagree with the model that sized the parts.
"""

# ---- wiring, proven on the bench 2026-11-08 ----
STEP_PIN, DIR_PIN, EN_PIN = {step}, {dir}, {en}
EN_ACTIVE_LOW = True          # TMC2209 EN is active low: 0 enables

# Which way the motor has to turn to ADVANCE the plunger into the barrel.
# Not knowable from the model: it depends on how the coil pairs landed in the
# connector. drive.selftest() measures it. If the carriage runs AWAY from the
# syringe, flip this to 0 and re-upload.
DIR_ADVANCE = 1

# ---- the drive train ----
MICROSTEP = {micro}
STEPS_PER_REV = {spr}         # 200 full steps x {micro}
SCREW_LEAD = {lead}           # mm per revolution, Tr8x8
STEPS_PER_MM = {spmm}         # {spr} / {lead}

# ---- the fluid ----
BORE_A = {bore}               # mm2, MEASURED 3000 / 25.0 mm between graduations
UL_PER_STEP = {ulstep}        # {bore} mm2 x {lead} mm / {spr} steps
BEAT_ML = {beat_ml}
BEAT_MM = {beat_mm}           # BEAT_ML * 1000 / BORE_A

# ---- limits ----
# TRAVEL is what the frame allows. SOFT_TRAVEL is what the BARREL allows, and
# it is the smaller of the two. Retracting past it drags the plunger seal out
# of the open end of a 5 mL barrel, which ends the experiment and the syringe.
# The firmware refuses to cross it. There is no endstop on this machine: the
# zero is declared by hand with set_zero() after parking the carriage.
TRAVEL_MM = {travel}
SOFT_TRAVEL_MM = {soft}
PEAK_RPM = {rpm}
MAX_SPS = {maxsps}            # hard ceiling on step rate, 1.5x the peak

# ---- the beat ----
# Piston DISPLACEMENT over one cycle, 0 retracted to 1 advanced. Not velocity.
# Generated by assembly.beat(), the same array the 3-D viewer animates, so the
# picture and the hardware play the same profile.
UPSTROKE_S = {upstroke}
UPSTROKE_FRAC = {upfrac}
EJECT_FRAC = {eject}
BEAT = {profile}
'''


def main():
    import datetime
    spr = 200 * MICROSTEP
    spmm = spr / S.SCREW_LEAD
    prof = A.beat()
    body = TEMPLATE.format(
        date=datetime.date.today().isoformat(),
        step=STEP_PIN, dir=DIR_PIN, en=EN_PIN,
        micro=MICROSTEP, spr=spr, lead=repr(S.SCREW_LEAD), spmm=repr(spmm),
        bore=repr(round(S.BORE_A, 4)),
        ulstep=repr(round(S.SCREW_LEAD / spr * S.BORE_A, 5)),
        beat_ml=repr(S.BEAT_ML), beat_mm=repr(round(S.BEAT_MM, 5)),
        travel=repr(S.TRAVEL), soft=repr(round(S.SOFT_TRAVEL, 3)),
        rpm=repr(round(S.PEAK_RPM, 1)),
        maxsps=int(S.PEAK_RPM / 60.0 * spr * 1.5),
        upstroke=repr(S.UPSTROKE_S), upfrac=repr(S.UPSTROKE_FRAC),
        eject=repr(A.EJECT_FRAC),
        profile=_wrap(prof))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(body)

    print("wrote %s" % OUT)
    print("  %d steps/mm, %.3f uL/step, beat %.3f mm = %d steps"
          % (spmm, S.SCREW_LEAD / spr * S.BORE_A, S.BEAT_MM,
             round(S.BEAT_MM * spmm)))
    print("  soft limit %.1f mm of the frame's %.0f mm"
          % (S.SOFT_TRAVEL, S.TRAVEL))
    print("  beat profile %d samples, peak %.3f" % (len(prof), max(prof)))
    rev = sum(1 for i in range(1, len(prof)) if prof[i] < prof[i - 1])
    print("  %d of %d samples move backward, so the profile DOES reverse"
          % (rev, len(prof) - 1))


def _wrap(seq, per=8):
    rows = [", ".join("%.4f" % v for v in seq[i:i + per])
            for i in range(0, len(seq), per)]
    return "(\n    " + ",\n    ".join(rows) + ")"


if __name__ == "__main__":
    sys.exit(main())
