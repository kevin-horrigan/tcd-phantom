# -*- coding: utf-8 -*-
"""Motor driver for the TCD phantom's pulsatile piston. Runs ON the Pico.

    import drive
    drive.selftest()            prove direction and wiring, 2 mm, slow
    drive.set_zero()            declare where the carriage is now
    drive.goto_mm(10)           park it
    drive.beat()                one beat
    drive.run(hr=60, beats=30)  thirty beats
    drive.off()                 de-energise

Every number comes from config.py, which is GENERATED from the model. Nothing
in this file knows the bore, the lead or the beat volume.

Three things this driver takes seriously, because each of them is a way to
lose an experiment quietly rather than loudly.

POSITION IS EXACT OR IT IS NOTHING. The step train is generated by PIO with
an exact pulse count per burst, never by a Python loop. A dropped step is not
a glitch here, it is 0.6 uL of stroke volume that never happened, and nothing
downstream would reveal it. Python chooses the counts; the state machine
guarantees them.

THERE IS NO ENDSTOP. The only position sensor on this machine is a paint mark,
and StallGuard cannot help because it works in StealthChop only, while this
drive wants SpreadCycle torque. So zero is DECLARED, by hand, with set_zero()
after parking the carriage. Everything after that is dead reckoning from a
count that is exact, which is the only reason dead reckoning is acceptable.

THE SOFT LIMIT IS THE BARREL, NOT THE FRAME. The frame allows 45 mm. The 5 mL
barrel allows less, and retracting past it pulls the plunger seal out of the
open end. The frame will happily drive straight through that point. This
refuses to.

Power-up order, every time:
    1. motor DISCONNECTED, 12 V on, Pico USB on, meter against GND
    2. 12 V off, connect the motor
    3. 12 V on, THEN USB
Never unplug the motor while VM is live. The coil dumps into the driver.

VREF needs VCC_IO, not just VM. Measured here: with 12 V on and the Pico
unplugged the wiper reads 0 V, and one outer leg of the pot sits at about
3.3 V. A reading of 0.00 V from a missing logic supply is indistinguishable
from a pot wound fully down, and the obvious response to zero is to turn it
UP. Motor disconnected is what makes this safe, not power removed.

Direction, measured on this board: CW raises VREF, CCW lowers it. An earlier
note here said the opposite, inherited rather than measured, and it caused a
false alarm. Find the end stop instead of trusting any claim, this one
included. A pot reading 0.00 V that will not go lower is at minimum, and
minimum is the harmless end to start from.

Set to 0.556 V on 2026-11-10, which is 0.393 A rms. syringe_drive.py derives
SET_I from that measurement rather than from the 0.53 V the design asked for.
"""
import time

import rp2
from machine import Pin

import config as C

SM_CLOCK = 1_000_000          # 1 us per PIO cycle
N_OVERHEAD = 6                # PIO cycles per step outside the delay loop
MIN_COUNT = 2                 # floor on the delay count, keeps the pulse legal


@rp2.asm_pio(set_init=rp2.PIO.OUT_LOW)
def _step_n():
    """Exactly N pulses at a fixed period. Two words per burst: N-1, period.

    PIO owns the counting, so a late or early sleep on the Python side cannot
    add or drop a step. That is the whole reason this is not a bit-banged
    loop: the position has to be arithmetic, not a hope.
    """
    pull(block)               # how many, minus one
    mov(y, osr)
    pull(block)               # period, stays in OSR for the whole burst
    label("step")
    mov(x, osr)
    set(pins, 1)[1]           # STEP high, 2 us
    set(pins, 0)
    label("hold")
    jmp(x_dec, "hold")
    jmp(y_dec, "step")


_en = Pin(C.EN_PIN, Pin.OUT, value=1 if C.EN_ACTIVE_LOW else 0)
_dir = Pin(C.DIR_PIN, Pin.OUT, value=0)
_sm = rp2.StateMachine(0, _step_n, freq=SM_CLOCK, set_base=Pin(C.STEP_PIN))
_sm.active(1)

pos = 0                       # microsteps from the declared zero, + is advance
_zeroed = False
_busy_us = 0                  # time.ticks_us() at which the last burst ends
_dir_now = None
clipped = 0                   # slices the rate ceiling had to slow down


def _count(sps):
    """PIO delay-loop count for a step rate, and the rate it really gives."""
    if sps <= 0:
        return None, 0.0
    n = int(round(SM_CLOCK / sps)) - N_OVERHEAD
    if n < MIN_COUNT:
        n = MIN_COUNT
    return n, SM_CLOCK / float(n + N_OVERHEAD)


def _wait_idle():
    """Block until the pulses already handed to PIO have actually come out.

    PIO does not report completion, so this does not ask: it knows how long
    each burst takes, because it chose the count and the period. Flipping DIR
    before a burst finishes would mis-direct the tail of it.
    """
    global _busy_us
    d = time.ticks_diff(_busy_us, time.ticks_us())
    if d > 0:
        time.sleep_us(d + 40)


def enable(on=True):
    _en.value((0 if on else 1) if C.EN_ACTIVE_LOW else (1 if on else 0))
    if on:
        time.sleep_ms(2)      # driver needs a moment before the first step


def off():
    _wait_idle()
    enable(False)


def set_zero():
    """Declare the carriage's present position as zero. No endstop exists."""
    global pos, _zeroed
    pos = 0
    _zeroed = True
    print("zero declared here. soft limit is %+.1f mm of retraction"
          % -C.SOFT_TRAVEL_MM)


def is_zeroed():
    """Has a zero been declared? Nothing may run a beat before it has.

    There is no endstop on this machine, so this is not a formality. Without
    a declared zero the soft limit has no datum to be measured from, and the
    firmware would happily retract the plunger seal out of the barrel.
    """
    return _zeroed


def mm():
    return pos / C.STEPS_PER_MM


def ul():
    return pos * C.UL_PER_STEP


def _burst(steps, sps):
    """Hand PIO an exact number of pulses in one direction. Returns steps done."""
    global pos, _busy_us, _dir_now, clipped
    if steps == 0:
        return 0
    want = 1 if steps > 0 else 0
    d = want if C.DIR_ADVANCE else 1 - want
    n = abs(steps)

    if sps > C.MAX_SPS:
        sps = C.MAX_SPS
        clipped += 1
    cnt, real = _count(sps)
    if cnt is None:
        return 0

    if d != _dir_now:
        _wait_idle()
        _dir.value(d)
        time.sleep_us(5)      # TMC2209 wants ~20 ns; 5 us is free
        _dir_now = d

    _sm.put(n - 1)
    _sm.put(cnt)
    dur = int(n * (cnt + N_OVERHEAD))
    now = time.ticks_us()
    if time.ticks_diff(_busy_us, now) < 0:
        _busy_us = now
    _busy_us = time.ticks_add(_busy_us, dur)
    pos += steps
    return steps


def _check(target_steps):
    """Refuse a move that would pull the seal out of the barrel."""
    lo = -int(C.SOFT_TRAVEL_MM * C.STEPS_PER_MM)
    hi = int(C.TRAVEL_MM * C.STEPS_PER_MM)
    if target_steps < lo:
        raise ValueError(
            "refusing: %.2f mm is past the %.1f mm soft limit. That retraction "
            "drags the plunger seal out of a %.0f mL barrel."
            % (target_steps / C.STEPS_PER_MM, -C.SOFT_TRAVEL_MM,
               C.SOFT_TRAVEL_MM * C.BORE_A / 1000.0))
    if target_steps > hi:
        raise ValueError("refusing: %.2f mm is past the frame's %.0f mm"
                         % (target_steps / C.STEPS_PER_MM, C.TRAVEL_MM))


def move_mm(dist, rpm=60.0, ramp=True):
    """Relative move. Positive advances the plunger into the barrel."""
    steps = int(round(dist * C.STEPS_PER_MM))
    if steps == 0:
        return 0.0
    if _zeroed:
        _check(pos + steps)
    enable(True)
    top = rpm / 60.0 * C.STEPS_PER_REV
    sgn = 1 if steps > 0 else -1
    n = abs(steps)
    if ramp and n > 60:
        # No stepper starts at speed. Three rungs each side is enough at the
        # rates this machine uses, and it keeps the position exact because
        # every rung is still an exact burst.
        lead = min(n // 3, 200)
        each = lead // 3
        for k in (1, 2, 3):
            _burst(sgn * each, top * (0.3 + 0.233 * k))
        _burst(sgn * (n - 2 * 3 * each), top)
        for k in (3, 2, 1):
            _burst(sgn * each, top * (0.3 + 0.233 * k))
    else:
        _burst(steps, top)
    _wait_idle()
    return mm()


def goto_mm(where, rpm=60.0):
    if not _zeroed:
        raise RuntimeError("no zero declared. park the carriage, set_zero()")
    return move_mm(where - mm(), rpm=rpm)


late_us = 0                   # worst slice lateness in the last beat


def beat(hr=60.0, slices=None):
    """One beat, played from the generated displacement profile.

    The profile is a POSITION curve, so each slice is a difference, and the
    rate for a slice is whatever delivers that difference inside the slice's
    share of the beat. The profile reverses twice over a cycle: once at the
    dicrotic notch, once into the refill, and _burst handles the direction
    change by waiting for PIO to finish rather than guessing.

    Python hands each burst to PIO and then paces itself to the slice
    boundary, so it stays about one slice ahead of the hardware. That gap is
    the whole timing budget, and it is MEASURED into late_us rather than
    assumed, because it is what anything else running on this chip eats
    into. On a Pico 2 W, servicing the wifi chip is exactly such a thing.

    Note carefully what jitter can and cannot do here. It cannot move the
    piston to the wrong place: PIO was handed an exact pulse count and will
    emit it whatever Python is doing, so position stays arithmetic. What it
    can do is deliver those pulses later than the profile asked, which
    distorts the SHAPE of the beat, and the shape is the entire product. So
    late_us is not a performance statistic, it is a correctness one.
    """
    global clipped, late_us
    prof = C.BEAT
    n = slices or len(prof)
    period = 60.0 / hr
    slice_s = period / (n - 1)
    slice_us = int(slice_s * 1e6)
    full = int(round(C.BEAT_MM * C.STEPS_PER_MM))
    start = pos
    clipped = 0
    worst = 0
    enable(True)

    want_prev = 0
    t0 = time.ticks_us()
    for i in range(1, n):
        want = int(round(prof[i * (len(prof) - 1) // (n - 1)] * full))
        d = want - want_prev
        want_prev = want
        if d:
            if _zeroed:
                _check(pos + d)
            _burst(d, abs(d) / slice_s)
        due = time.ticks_add(t0, i * slice_us)
        lag = time.ticks_diff(time.ticks_us(), due)
        if lag < 0:
            time.sleep_us(-lag)
        elif lag > worst:
            worst = lag
    late_us = worst
    _wait_idle()
    drift = pos - start
    if drift:
        _burst(-drift, 400.0)         # a beat must net to zero travel
        _wait_idle()
    return drift


def run(hr=60.0, beats=10):
    """Play a train of beats, then report what the rate ceiling cost."""
    t0 = time.ticks_ms()
    total_clip = 0
    try:
        for _ in range(beats):
            beat(hr)
            total_clip += clipped
    finally:
        off()
    el = time.ticks_diff(time.ticks_ms(), t0) / 1000.0
    print("%d beats at %.0f bpm in %.2f s (expected %.2f)"
          % (beats, hr, el, beats * 60.0 / hr))
    print("position %+.3f mm, %+.1f uL from zero" % (mm(), ul()))
    if total_clip:
        print("WARNING: %d slices hit the %d steps/s ceiling. The upstroke was"
              % (total_clip, C.MAX_SPS))
        print("slower than commanded, so the beat is not the profile.")
    else:
        print("no slice hit the rate ceiling, so the profile was played whole")


def selftest(revs=0.5, rpm=30.0):
    """Half a shaft revolution, forward, and STOP there. Then read the mark.

    This does NOT come back, and that is the entire design of it.

    An out-and-back move cannot detect the error this test exists to catch.
    If microstepping is really 16 rather than the 8 the config assumes, the
    shaft turns half as far out and half as far back and returns to exactly
    where it started, looking perfect. The return leg cancels precisely the
    fault being hunted. An earlier version of this function did that, and was
    a demonstration dressed as a test.

    Watching a mid-move pause would work, but hangs a correctness check on a
    human catching a 600 ms window, which is a bad place to put it. Stopping
    instead costs nothing and the evidence then sits still to be read.

    Mark the shaft, run it, and look at where the mark ends up:

        180 degrees, opposite the start   8 microsteps, config is right
        90 degrees, a quarter turn        16 microsteps, config is WRONG
        unmoved                           it never turned, see below

    The 16 case matters more than it looks. It is not a glitch, it is a
    factor of two on every volume this machine will ever deliver, with a
    waveform that looks entirely healthy. Nothing downstream would reveal it.
    MS1/MS2 both grounded is 8 on a TMC2209 and 16 on a TMC2208, and the
    carriers look alike.

    Call back() to return the shaft when you have read it.
    """
    steps = int(round(revs * C.STEPS_PER_REV))
    print("config: %d steps/mm, %.3f uL/step, beat %.3f mm = %d steps"
          % (C.STEPS_PER_MM, C.UL_PER_STEP, C.BEAT_MM,
             round(C.BEAT_MM * C.STEPS_PER_MM)))
    print("pins STEP=%d DIR=%d EN=%d, DIR_ADVANCE=%d"
          % (C.STEP_PIN, C.DIR_PIN, C.EN_PIN, C.DIR_ADVANCE))
    print("")
    print("commanding %d microsteps. If the config is right that is %.2f"
          % (steps, revs))
    print("shaft revolutions, %.0f degrees, taking about %.1f s at %.0f rpm."
          % (revs * 360.0, abs(steps) / (rpm / 60.0 * C.STEPS_PER_REV), rpm))
    print("It will STOP there and stay stopped. Mark the shaft first.")
    enable(True)
    _burst(steps, rpm / 60.0 * C.STEPS_PER_REV)
    _wait_idle()
    off()
    print("")
    print("Where did the mark stop?")
    print("  %3.0f deg, opposite the start -> %d microsteps, config is right"
          % (revs * 360.0, C.MICROSTEP))
    print("  %3.0f deg, half as far        -> %d microsteps, config is WRONG."
          % (revs * 180.0, C.MICROSTEP * 2))
    print("                              Every volume would be out by 2x and")
    print("                              the waveform would look fine. Tell me.")
    print("  did not move             -> buzzing means the coil pairs are")
    print("                              split: a stepper's two coils go")
    print("                              A1/A2 and B1/B2, never A1/B1.")
    print("                              Silence means no STEP, EN or VM.")
    print("  stuttered or skipped     -> VREF too low for this rate.")
    print("")
    print("Which way did it turn, seen from the shaft end? I need that for")
    print("DIR_ADVANCE once the screw is fitted. Then: drive.back()")


def back(revs=0.5, rpm=30.0):
    """Undo selftest. Separate on purpose, so the evidence sits still first."""
    _burst(-int(round(revs * C.STEPS_PER_REV)), rpm / 60.0 * C.STEPS_PER_REV)
    _wait_idle()
    off()
    print("returned %.2f revolutions" % revs)
